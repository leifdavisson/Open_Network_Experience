    @verifies("REQ-PRB-010")
    def test_discover_local_resolvers_standard_and_deduplication(self):
        """Verifies parsing of nameservers with comments, other directives, and deduplication."""
        resolv_content = (
            "# Generated by NetworkManager\n"
            "search corp.example.com\n"
            "nameserver 10.100.1.1\n"
            "nameserver 10.100.1.2\n"
            "nameserver 10.100.1.1  # Duplicate entry\n"
            "options edns0 trust-ad\n"
            "nameserver 192.168.1.254\n"
        )
        with patch("os.path.exists", return_value=True), \
             patch("builtins.open", mock_open(read_data=resolv_content)):
            resolvers = dns_multi_resolver_probe.discover_local_resolvers()

        expected = [
            {"name": "Local-DNS (10.100.1.1)", "ip": "10.100.1.1", "is_public": False},
            {"name": "Local-DNS (10.100.1.2)", "ip": "10.100.1.2", "is_public": False},
            {"name": "Local-DNS (192.168.1.254)", "ip": "192.168.1.254", "is_public": False},
        ]
        self.assertEqual(resolvers, expected)

