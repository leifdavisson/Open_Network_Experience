    @verifies("REQ-PRB-010")
    @patch("dns_multi_resolver_probe.probe_dns_server")
    @patch("dns_multi_resolver_probe.discover_local_resolvers")
    def test_run_multi_resolver_probes(self, mock_discover, mock_probe):
        """Verifies orchestration across both discovered local resolvers and public resolvers."""
        mock_discover.return_value = [
            {"name": "Local-DNS (10.0.0.1)", "ip": "10.0.0.1", "is_public": False}
        ]
        mock_probe.return_value = {
            "status": 1,
            "latency_seconds": 0.012,
            "rcode": 0,
            "rcode_str": "NOERROR"
        }

        results = dns_multi_resolver_probe.run_multi_resolver_probes(interface="eth0")

        # 1 local + 4 public = 5 resolvers, 4 domains each = 20 probe executions
        total_resolvers = 1 + len(dns_multi_resolver_probe.PUBLIC_DNS_PROVIDERS)
        total_domains = len(dns_multi_resolver_probe.DEFAULT_BENCHMARK_DOMAINS)
        self.assertEqual(len(results), total_resolvers * total_domains)

        self.assertEqual(mock_probe.call_count, 20)
        # Check structure of first result
        first = results[0]
        self.assertEqual(first["resolver_name"], "Local-DNS (10.0.0.1)")
        self.assertEqual(first["resolver_ip"], "10.0.0.1")
        self.assertEqual(first["is_public"], 0)
        self.assertEqual(first["domain"], dns_multi_resolver_probe.DEFAULT_BENCHMARK_DOMAINS[0]["domain"])
        self.assertEqual(first["status"], 1)

    @verifies("REQ-PRB-010")
    def test_write_metrics_atomic_file_emission(self):
        """Verifies atomic write of Prometheus metrics with correct labels and formats."""
        sample_results = [
            {
                "resolver_name": "Local-DNS (10.0.0.1)",
                "resolver_ip": "10.0.0.1",
                "is_public": 0,
                "domain": "google.com",
                "status": 1,
                "latency_seconds": 0.0123,
                "rcode": 0,
                "rcode_str": "NOERROR"
            },
            {
                "resolver_name": "Cloudflare-Primary",
                "resolver_ip": "1.1.1.1",
                "is_public": 1,
                "domain": "canvas.net",
                "status": 0,
                "latency_seconds": 2.0,
                "rcode": -1,
                "rcode_str": "TIMEOUT"
            }
        ]

        dns_multi_resolver_probe.write_metrics(sample_results, self.prom_file)

        self.assertTrue(os.path.exists(self.prom_file))
        with open(self.prom_file, "r") as f:
            content = f.read()

        self.assertIn("# HELP openux_dns_resolver_status", content)
        self.assertIn("# TYPE openux_dns_resolver_status gauge", content)
        self.assertIn("# HELP openux_dns_resolver_latency_seconds", content)
        self.assertIn("# HELP openux_dns_resolver_rcode", content)

        self.assertIn('openux_dns_resolver_status{resolver="Local-DNS (10.0.0.1)",ip="10.0.0.1",domain="google.com",public="0"} 1', content)
        self.assertIn('openux_dns_resolver_latency_seconds{resolver="Local-DNS (10.0.0.1)",ip="10.0.0.1",domain="google.com",public="0"} 0.0123', content)
        self.assertIn('openux_dns_resolver_rcode{resolver="Local-DNS (10.0.0.1)",ip="10.0.0.1",domain="google.com",public="0"} 0', content)

        self.assertIn('openux_dns_resolver_status{resolver="Cloudflare-Primary",ip="1.1.1.1",domain="canvas.net",public="1"} 0', content)
        self.assertIn('openux_dns_resolver_latency_seconds{resolver="Cloudflare-Primary",ip="1.1.1.1",domain="canvas.net",public="1"} 2.0000', content)
        self.assertIn('openux_dns_resolver_rcode{resolver="Cloudflare-Primary",ip="1.1.1.1",domain="canvas.net",public="1"} -1', content)

