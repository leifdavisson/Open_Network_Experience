    @verifies("REQ-PRB-010")
    @patch("socket.socket")
    def test_probe_dns_server_success(self, mock_socket_cls):
        """Verifies successful DNS resolution benchmark measuring positive latency and NOERROR."""
        mock_sock = MagicMock()
        mock_socket_cls.return_value = mock_sock
        resp_packet = b"\x12\x34\x81\x80\x00\x01\x00\x01\x00\x00\x00\x00"
        mock_sock.recvfrom.return_value = (resp_packet, ("1.1.1.1", 53))

        with patch("time.time", side_effect=[100.000, 100.015]):
            result = dns_multi_resolver_probe.probe_dns_server("1.1.1.1", "google.com", timeout_sec=2.0)

        mock_sock.settimeout.assert_called_once_with(2.0)
        mock_sock.sendto.assert_called_once()
        mock_sock.close.assert_called_once()
        self.assertEqual(result["status"], 1)
        self.assertAlmostEqual(result["latency_seconds"], 0.015, places=3)
        self.assertEqual(result["rcode"], 0)
        self.assertEqual(result["rcode_str"], "NOERROR")

