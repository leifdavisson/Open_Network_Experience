    @verifies("REQ-PRB-010")
    def test_build_dns_query_packet_structure(self):
        """Verifies RFC 1035 UDP query serialization for domain labels and A record type."""
        domain = "google.com"
        with patch("random.randint", return_value=0x1234):
            packet = dns_multi_resolver_probe.build_dns_query(domain, query_type=1)

        # Header: TX_ID (0x1234), Flags (0x0100 - standard query, recursion desired), QDCOUNT (0x0001)
        expected_header = b"\x12\x34\x01\x00\x00\x01\x00\x00\x00\x00\x00\x00"
        self.assertEqual(packet[:12], expected_header)

        # Question: \x06 google \x03 com \x00 \x00\x01 (Type A) \x00\x01 (Class IN)
        expected_question = b"\x06google\x03com\x00\x00\x01\x00\x01"
        self.assertEqual(packet[12:], expected_question)

    @verifies("REQ-PRB-010")
    def test_parse_dns_response_rcodes(self):
        """Verifies RCODE extraction from response header flags."""
        # Short packet (< 4 bytes)
        rcode, rcode_str = dns_multi_resolver_probe.parse_dns_response(b"\x12\x34\x81")
        self.assertEqual(rcode, -1)
        self.assertEqual(rcode_str, "MALFORMED")

        # NOERROR (rcode = 0, standard response flags 0x8180)
        resp_noerror = b"\x12\x34\x81\x80\x00\x01\x00\x01\x00\x00\x00\x00"
        self.assertEqual(dns_multi_resolver_probe.parse_dns_response(resp_noerror), (0, "NOERROR"))

        # FORMERR (rcode = 1, flags 0x8181)
        resp_formerr = b"\x12\x34\x81\x81\x00\x01\x00\x00\x00\x00\x00\x00"
        self.assertEqual(dns_multi_resolver_probe.parse_dns_response(resp_formerr), (1, "FORMERR"))

        # SERVFAIL (rcode = 2, flags 0x8182)
        resp_servfail = b"\x12\x34\x81\x82\x00\x01\x00\x00\x00\x00\x00\x00"
        self.assertEqual(dns_multi_resolver_probe.parse_dns_response(resp_servfail), (2, "SERVFAIL"))

        # NXDOMAIN (rcode = 3, flags 0x8183)
        resp_nxdomain = b"\x12\x34\x81\x83\x00\x01\x00\x00\x00\x00\x00\x00"
        self.assertEqual(dns_multi_resolver_probe.parse_dns_response(resp_nxdomain), (3, "NXDOMAIN"))

        # NOTIMP (rcode = 4, flags 0x8184)
        resp_notimp = b"\x12\x34\x81\x84\x00\x01\x00\x00\x00\x00\x00\x00"
        self.assertEqual(dns_multi_resolver_probe.parse_dns_response(resp_notimp), (4, "NOTIMP"))

        # REFUSED (rcode = 5, flags 0x8185)
        resp_refused = b"\x12\x34\x81\x85\x00\x01\x00\x00\x00\x00\x00\x00"
        self.assertEqual(dns_multi_resolver_probe.parse_dns_response(resp_refused), (5, "REFUSED"))

        # Unmapped RCODE (e.g. 9)
        resp_other = b"\x12\x34\x81\x89\x00\x01\x00\x00\x00\x00\x00\x00"
        self.assertEqual(dns_multi_resolver_probe.parse_dns_response(resp_other), (9, "RCODE_9"))

